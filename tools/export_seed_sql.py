"""Write backend/supabase/seed.sql (positions, scoring weights, bonus bands) from engine/config.json.

Run: python3 tools/export_seed_sql.py
The workbook stays the place to tune weights; export_config.py updates config.json, this keeps the database in step.
"""
import json
from pathlib import Path
import sys; sys.path.insert(0, ".")
from engine import load_config, profile_for

cfg = load_config()
q = lambda s: "'" + str(s).replace("'", "''") + "'"
lines = ["-- Generated by tools/export_seed_sql.py from engine/config.json. Do not edit by hand.", "begin;"]
rows = []
for key, (avg, sd) in cfg["baselines_fallback"].items():
    sport, pos = key.split("|")
    rows.append(f"({q(sport)}::sport, {q(pos)}, {q(profile_for(sport, pos))}, {cfg['min_games'][key]}, {avg}, {sd})")
lines.append("insert into positions (sport, position, profile, min_games, fallback_avg, fallback_sd) values\n  " + ",\n  ".join(rows) + "\non conflict (sport, position) do update set profile = excluded.profile, min_games = excluded.min_games, fallback_avg = excluded.fallback_avg, fallback_sd = excluded.fallback_sd;")
rows = [f"({q(k.split('|', 1)[0])}, {q(k.split('|', 1)[1])}, {w})" for k, w in cfg["weights"].items()]
lines.append("insert into scoring_weights (profile, stat, weight) values\n  " + ",\n  ".join(rows) + "\non conflict (profile, stat) do update set weight = excluded.weight;")
rows = [f"({s}, {p})" for s, p in cfg["bonus_bands"]]
lines.append("insert into bonus_bands (start_place, points) values " + ", ".join(rows) + "\non conflict (start_place) do update set points = excluded.points;")
f1 = cfg["f1"]
lines.append("insert into f1_points (kind, place, points) values\n  " + ",\n  ".join(
    [f"('race', {p}, {v})" for p, v in f1["race_points"].items()] + [f"('sprint', {i + 1}, {v})" for i, v in enumerate(f1["sprint_points"])] +
    [f"('pole', 1, {f1['pole_bonus']})", f"('front_row', 2, {f1['p2_p3_bonus']})", f"('front_row', 3, {f1['p2_p3_bonus']})"]) +
    "\non conflict (kind, place) do update set points = excluded.points;")
lines.append("commit;")
out = Path("backend/supabase/seed.sql")
out.write_text("\n".join(lines) + "\n")
print("wrote", out)
